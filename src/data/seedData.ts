function createSeedEvaluation(
  decision: 'ALLOW' | 'APPROVAL_REQUIRED' | 'BLOCK',
  riskScore: number,
  reasons: string[],
  signalKeys: Array<{ key: any; label: string; points: number; description: string }>
): EvaluationResult {
  const isCompromise = riskScore >= 95;
  const isKnown = !signalKeys.some(s => s.key === 'new_merchant');
  const catAllowed = !signalKeys.some(s => s.key === 'restricted_category');
  const withinTx = !signalKeys.some(s => s.key === 'transaction_limit');
  const withinDaily = !signalKeys.some(s => s.key === 'daily_budget');
  const amountAnom = signalKeys.some(s => s.key === 'amount_anomaly');
  const velAnom = signalKeys.some(s => s.key === 'velocity_anomaly');
  const timeAnom = signalKeys.some(s => s.key === 'unusual_time');
  const isSuspended = signalKeys.some(s => s.key === 'agent_suspended');

  const triggeredSignals = signalKeys.map(s => ({
    key: s.key,
    label: s.label,
    points: s.points,
    description: s.description,
    triggered: true,
  }));

  return {
    decision,
    riskScore,
    signals: triggeredSignals,
    triggeredSignals,
    reasons,
    isCompromise,
    checks: {
      agentAuthorized: catAllowed && !isSuspended,
      categoryAllowed: catAllowed,
      withinTxLimit: withinTx,
      withinDailyBudget: withinDaily,
      isKnownMerchant: isKnown,
      amountAnomaly: amountAnom,
      velocityAnomaly: velAnom,
      timeAnomaly: timeAnom,
      isSuspended,
    },
    evaluatedAt: new Date().toISOString(),
  };
}

